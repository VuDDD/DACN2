import os
import shutil
import uuid
import logging
from typing import Tuple, Optional
from fastapi import UploadFile, HTTPException, status
from app.core.config import settings

logger = logging.getLogger("retina_storage")

# Allowed image MIME types and extensions for retinal imaging
ALLOWED_MIME_TYPES = {
    "image/jpeg",
    "image/png",
    "image/tiff",
    "image/bmp",
    "image/gif",
    "application/octet-stream", # for raw tiff uploads
}
ALLOWED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".tif", ".tiff", ".bmp", ".gif"}
MAX_FILE_SIZE = 30 * 1024 * 1024 # 30 Megabytes

class StorageService:
    def __init__(self):
        self.local_root = os.path.abspath(settings.STORAGE_DIR)
        os.makedirs(self.local_root, exist_ok=True)
        self.minio_client = None
        self._init_minio()

    def _init_minio(self):
        """Attempts to connect to MinIO if minio library is present and endpoint is reachable."""
        try:
            from minio import Minio
            client = Minio(
                settings.MINIO_ENDPOINT,
                access_key=settings.MINIO_ACCESS_KEY,
                secret_key=settings.MINIO_SECRET_KEY,
                secure=settings.MINIO_SECURE
            )
            # Check bucket presence
            if not client.bucket_exists(settings.MINIO_BUCKET_NAME):
                client.make_bucket(settings.MINIO_BUCKET_NAME)
            self.minio_client = client
            logger.info(f"Connected to MinIO at {settings.MINIO_ENDPOINT}, bucket: {settings.MINIO_BUCKET_NAME}")
        except Exception as e:
            logger.warning(f"MinIO not available, using high-speed local disk storage at {self.local_root}: {e}")
            self.minio_client = None

    def validate_file(self, file: UploadFile) -> str:
        """Validates extension and returns file extension."""
        ext = os.path.splitext(file.filename)[1].lower()
        if ext not in ALLOWED_EXTENSIONS:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Invalid file extension: '{ext}'. Allowed: {', '.join(sorted(ALLOWED_EXTENSIONS))}"
            )
        return ext

    async def save_upload(self, file: UploadFile, subfolder: str = "images") -> Tuple[str, str]:
        """
        Saves uploaded file.
        Returns: (relative_storage_path, absolute_file_path)
        """
        ext = self.validate_file(file)
        unique_name = f"{uuid.uuid4().hex}{ext}"
        target_dir = os.path.join(self.local_root, subfolder)
        os.makedirs(target_dir, exist_ok=True)
        abs_path = os.path.join(target_dir, unique_name)

        # Write to disk with size validation
        size = 0
        with open(abs_path, "wb") as buffer:
            while chunk := await file.read(1024 * 1024):
                size += len(chunk)
                if size > MAX_FILE_SIZE:
                    buffer.close()
                    os.remove(abs_path)
                    raise HTTPException(
                        status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
                        detail="File exceeds maximum allowed size of 30MB."
                    )
                buffer.write(chunk)
        
        # MinIO sync if available
        rel_key = f"{subfolder}/{unique_name}"
        if self.minio_client:
            try:
                self.minio_client.fput_object(
                    settings.MINIO_BUCKET_NAME,
                    rel_key,
                    abs_path
                )
            except Exception as e:
                logger.warning(f"Failed to sync file to MinIO: {e}")

        # Return relative URL path and absolute path
        return f"/api/images/serve/{subfolder}/{unique_name}", abs_path

    def save_bytes(self, data: bytes, filename: str, subfolder: str = "masks") -> Tuple[str, str]:
        """Saves generated byte buffer (e.g. masks, plots, reports)."""
        target_dir = os.path.join(self.local_root, subfolder)
        os.makedirs(target_dir, exist_ok=True)
        abs_path = os.path.join(target_dir, filename)

        with open(abs_path, "wb") as f:
            f.write(data)

        rel_key = f"{subfolder}/{filename}"
        if self.minio_client:
            try:
                self.minio_client.fput_object(
                    settings.MINIO_BUCKET_NAME,
                    rel_key,
                    abs_path
                )
            except Exception as e:
                logger.warning(f"Failed to sync bytes to MinIO: {e}")

        return f"/api/images/serve/{subfolder}/{filename}", abs_path

    def get_absolute_path(self, relative_url: str) -> Optional[str]:
        """Resolves relative URL or relative key to absolute local file path."""
        if not relative_url:
            return None
        # Handle '/api/images/serve/subfolder/file.ext'
        clean = relative_url.replace("/api/images/serve/", "")
        clean = clean.replace("/", os.sep)
        full_path = os.path.join(self.local_root, clean)
        if os.path.exists(full_path):
            return full_path
        return None

storage_service = StorageService()

